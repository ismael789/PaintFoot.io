create or replace function public.ensure_paintfoot_profile(p_username text)
returns table(id uuid, username text, global_color text)
language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_name text := left(regexp_replace(trim(coalesce(p_username, 'Jugador')), '\s+', ' ', 'g'), 30);
  v_palette text[] := array[
    '#208AEF','#E53935','#7C4DFF','#00897B','#FB8C00','#D81B60',
    '#00ACC1','#43A047','#FDD835','#8E24AA','#F4511E','#3949AB',
    '#7CB342','#C2185B','#00838F','#6D4C41','#5E35B1','#039BE5'
  ];
  v_color text;
begin
  if v_user_id is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if char_length(v_name) < 2 then v_name := 'Jugador'; end if;
  select p.global_color into v_color from public.paintfoot_profiles p where p.id = v_user_id;
  if v_color is null then
    v_color := v_palette[1 + (abs(hashtext(v_user_id::text)) % array_length(v_palette, 1))];
    if exists(select 1 from public.paintfoot_profiles where global_color = v_color) then
      v_color := '#' || upper(substring(md5(v_user_id::text) from 1 for 6));
    end if;
  end if;
  insert into public.paintfoot_profiles(id, username, global_color)
  values(v_user_id, v_name, v_color)
  on conflict (id) do update set username = excluded.username, updated_at = now();
  return query select p.id, p.username, p.global_color
    from public.paintfoot_profiles p where p.id = v_user_id;
end;
$$;

create or replace function public.get_global_territories(
  p_region_ids text[], p_limit integer default 200, p_offset integer default 0
) returns table(
  id text, owner_id uuid, owner_name text, owner_color text, status text,
  payload jsonb, region_ids text[], shield_expires_at timestamptz
)
language sql security definer set search_path = '' stable
as $$
  select t.id, t.owner_id, coalesce(p.username, 'Jugador'),
    coalesce(p.global_color, t.player_color),
    case
      when t.shield_expires_at > now() then 'protected'
      when t.status = 'protected' then 'vulnerable'
      else t.status
    end,
    t.payload, t.region_ids, t.shield_expires_at
  from public.territories t
  left join public.paintfoot_profiles p on p.id = t.owner_id
  where auth.uid() is not null
    and t.status not in ('rejected', 'pending_validation', 'pending_capture')
    and t.region_ids && coalesce(p_region_ids, '{}'::text[])
  order by t.updated_at desc, t.id
  limit least(greatest(coalesce(p_limit, 200), 1), 200)
  offset greatest(coalesce(p_offset, 0), 0);
$$;

create or replace function public.publish_player_presence(
  p_region_id text, p_latitude double precision, p_longitude double precision,
  p_accuracy double precision default null, p_heading double precision default null,
  p_speed double precision default null, p_state text default 'playing',
  p_trail jsonb default '[]'::jsonb
) returns void language plpgsql security definer set search_path = ''
as $$
declare v_user_id uuid := auth.uid();
begin
  if v_user_id is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then
    raise exception 'INVALID_COORDINATE' using errcode = '22023';
  end if;
  delete from public.player_presence where updated_at < now() - interval '2 minutes';
  if jsonb_typeof(coalesce(p_trail, '[]'::jsonb)) <> 'array'
    or jsonb_array_length(coalesce(p_trail, '[]'::jsonb)) > 24 then
    raise exception 'INVALID_PRESENCE_TRAIL' using errcode = '22023';
  end if;
  insert into public.player_presence
    (user_id, region_id, latitude, longitude, accuracy, heading, speed, trail, state, updated_at)
  values
    (v_user_id, left(p_region_id, 80), p_latitude, p_longitude, p_accuracy,
     p_heading, p_speed, coalesce(p_trail, '[]'::jsonb),
     left(coalesce(p_state, 'playing'), 30), now())
  on conflict (user_id) do update set
    region_id = excluded.region_id, latitude = excluded.latitude,
    longitude = excluded.longitude, accuracy = excluded.accuracy,
    heading = excluded.heading, speed = excluded.speed, trail = excluded.trail,
    state = excluded.state, updated_at = now();
end;
$$;

create or replace function public.get_nearby_player_presence(p_region_ids text[])
returns table(
  id uuid, name text, color text, latitude double precision,
  longitude double precision, accuracy double precision, heading double precision,
  speed double precision, region_id text, updated_at_ms double precision, trail jsonb
)
language sql security definer set search_path = '' stable
as $$
  select pp.user_id, p.username, p.global_color, pp.latitude, pp.longitude,
    pp.accuracy, pp.heading, pp.speed, pp.region_id,
    extract(epoch from pp.updated_at) * 1000, pp.trail
  from public.player_presence pp
  join public.paintfoot_profiles p on p.id = pp.user_id
  where auth.uid() is not null
    and pp.user_id <> auth.uid()
    and pp.region_id = any(coalesce(p_region_ids, '{}'::text[]))
    and pp.updated_at > now() - interval '45 seconds'
  order by pp.updated_at desc
  limit 200;
$$;

create or replace function public.cleanup_stale_player_presence()
returns integer language plpgsql security definer set search_path = ''
as $$
declare v_count integer;
begin
  delete from public.player_presence where updated_at < now() - interval '2 minutes';
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

create or replace function public.clear_player_presence()
returns void language sql security definer set search_path = ''
as $$
  delete from public.player_presence where user_id = auth.uid();
$$;

create or replace function public.confirm_territory_capture(
  p_operation_id text,
  p_candidate_id text,
  p_target_territory_id text,
  p_capture_session_id text,
  p_candidate jsonb
) returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_profile public.paintfoot_profiles%rowtype;
  v_target public.territories%rowtype;
  v_result public.territories%rowtype;
  v_signature text := p_candidate->>'signature';
  v_area double precision := coalesce((p_candidate->>'areaM2')::double precision, 0);
  v_region_ids text[] := array(select jsonb_array_elements_text(coalesce(p_candidate->'regionIds','[]'::jsonb)));
  v_point_count integer := 0;
  v_reason text;
  v_payload jsonb;
  v_target_found boolean := false;
begin
  if v_user_id is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if coalesce(p_operation_id, '') = '' or coalesce(v_signature, '') = '' then
    raise exception 'INVALID_CAPTURE' using errcode = '22023';
  end if;
  select * into v_profile from public.paintfoot_profiles where id = v_user_id;
  if not found then raise exception 'PROFILE_REQUIRED' using errcode = '42501'; end if;

  if exists(select 1 from public.paintfoot_sync_operations where operation_id = p_operation_id) then
    select * into v_result from public.territories
      where id = coalesce(p_target_territory_id, p_candidate_id);
    return jsonb_build_object('status', v_result.status, 'duplicate', true,
      'territory', jsonb_build_object(
        'id',v_result.id,'owner_id',v_result.owner_id,'owner_name',v_profile.username,
        'owner_color',v_result.player_color,'status',v_result.status,'payload',v_result.payload,
        'region_ids',v_result.region_ids,'shield_expires_at',v_result.shield_expires_at));
  end if;

  if p_capture_session_id is not null then
    if not exists(select 1 from public.tracking_sessions where id = p_capture_session_id and user_id = v_user_id) then
      raise exception 'SESSION_NOT_SYNCED' using errcode = '23503';
    end if;
    select count(*) into v_point_count from public.tracking_points
      where session_id = p_capture_session_id and user_id = v_user_id;
    if v_point_count < 3 then raise exception 'INCOMPLETE_PERIMETER' using errcode = '22023'; end if;
  else
    raise exception 'CAPTURE_SESSION_REQUIRED' using errcode = '22023';
  end if;
  if v_area < 200 or jsonb_array_length(coalesce(p_candidate->'coordinates','[]'::jsonb)) < 3 then
    raise exception 'INVALID_TERRITORY' using errcode = '22023';
  end if;

  if p_target_territory_id is not null then
    select * into v_target from public.territories where id = p_target_territory_id for update;
  else
    select * into v_target from public.territories
      where signature = v_signature and status <> 'rejected' for update;
  end if;
  v_target_found := found;

  if v_target_found and v_target.owner_id <> v_user_id and (
    v_target.shield_expires_at > now() or
    to_timestamp(coalesce((v_target.payload->'shield'->>'expiresAt')::double precision, 0) / 1000.0) > now()
  ) then
    raise exception 'TERRITORY_PROTECTED' using errcode = '42501';
  end if;

  v_payload := p_candidate || jsonb_build_object(
    'playerId', v_user_id::text,
    'globalOwnerId', v_user_id::text,
    'playerColor', v_profile.global_color,
    'color', v_profile.global_color,
    'owner', v_profile.username,
    'status', 'confirmed'
  );

  if v_target_found then
    v_reason := case when v_target.owner_id = v_user_id then 'owner_refresh' else 'full_perimeter_capture' end;
    update public.territories set
      owner_id = v_user_id, user_id = v_user_id, player_color = v_profile.global_color,
      geometry = p_candidate->'polygon', area = v_area, payload = v_payload,
      status = 'confirmed', signature = v_signature, region_ids = v_region_ids,
      primary_region = v_region_ids[1], capture_session_id = p_capture_session_id,
      shield_expires_at = null, revision = revision + 1, updated_at = now()
    where id = v_target.id returning * into v_result;
  else
    v_reason := 'new_territory';
    insert into public.territories
      (id,user_id,owner_id,geometry,area,player_color,status,payload,signature,
       region_ids,primary_region,capture_session_id,local_created_at,updated_at)
    values
      (p_candidate_id,v_user_id,v_user_id,p_candidate->'polygon',v_area,
       v_profile.global_color,'confirmed',v_payload,v_signature,v_region_ids,
       v_region_ids[1],p_capture_session_id,
       to_timestamp(coalesce((p_candidate->>'createdAt')::double precision,
         extract(epoch from now())*1000)/1000.0),now())
    returning * into v_result;
  end if;

  insert into public.territory_ownership_history
    (territory_id,previous_owner_id,new_owner_id,capture_session_id,area,reason,operation_id)
  values
    (v_result.id,v_target.owner_id,v_user_id,p_capture_session_id,v_area,v_reason,p_operation_id);
  insert into public.paintfoot_sync_operations(operation_id,user_id,action,entity_type,entity_id)
  values(p_operation_id,v_user_id,'CAPTURE_TERRITORY','territory',v_result.id);

  return jsonb_build_object('status','confirmed','duplicate',false,
    'territory',jsonb_build_object(
      'id',v_result.id,'owner_id',v_result.owner_id,'owner_name',v_profile.username,
      'owner_color',v_result.player_color,'status',v_result.status,'payload',v_result.payload,
      'region_ids',v_result.region_ids,'shield_expires_at',v_result.shield_expires_at));
exception
  when unique_violation then
    insert into public.territory_capture_disputes
      (operation_id,candidate_id,target_territory_id,user_id,signature,candidate_payload)
    values
      (p_operation_id,p_candidate_id,p_target_territory_id,v_user_id,v_signature,p_candidate)
    on conflict (operation_id) do nothing;
    return jsonb_build_object('status','disputed','duplicate',false);
end;
$$;

create or replace function public.set_owned_territory_shield(
  p_territory_id text, p_expires_at_ms double precision, p_duration_hours double precision
) returns void language plpgsql security definer set search_path = ''
as $$
declare v_user_id uuid := auth.uid(); v_expires_at timestamptz;
begin
  if v_user_id is null then raise exception 'AUTH_REQUIRED' using errcode = '42501'; end if;
  if p_expires_at_ms is null then
    update public.territories set shield_expires_at = null, updated_at = now()
      where id = p_territory_id and owner_id = v_user_id;
    return;
  end if;
  if p_duration_hours is null or p_duration_hours <= 0 or p_duration_hours > 36 then
    raise exception 'INVALID_SHIELD_DURATION' using errcode = '22023';
  end if;
  v_expires_at := to_timestamp(p_expires_at_ms / 1000.0);
  if v_expires_at > now() + interval '36 hours' then
    raise exception 'INVALID_SHIELD_EXPIRATION' using errcode = '22023';
  end if;
  update public.territories set shield_expires_at = v_expires_at,
    status = case when v_expires_at > now() then 'protected' else 'vulnerable' end,
    updated_at = now()
  where id = p_territory_id and owner_id = v_user_id;
  if not found then raise exception 'NOT_TERRITORY_OWNER' using errcode = '42501'; end if;
end;
$$;

