alter table public.territories add column if not exists signature text;
alter table public.territories add column if not exists region_ids text[] not null default '{}';
alter table public.territories add column if not exists primary_region text;
alter table public.territories add column if not exists shield_expires_at timestamptz;
alter table public.territories add column if not exists capture_session_id text;
alter table public.territories add column if not exists revision bigint not null default 1;

update public.territories
set owner_id = user_id
where owner_id is null and user_id is not null;

create table if not exists public.territory_ownership_history (
  id bigint generated by default as identity primary key,
  territory_id text not null references public.territories(id) on delete cascade,
  previous_owner_id uuid references auth.users(id),
  new_owner_id uuid not null references auth.users(id),
  captured_at timestamptz not null default now(),
  capture_session_id text,
  area double precision not null default 0,
  reason text not null,
  operation_id text not null unique
);

create table if not exists public.player_presence (
  user_id uuid primary key references auth.users(id) on delete cascade,
  region_id text not null,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy double precision,
  heading double precision,
  speed double precision,
  trail jsonb not null default '[]'::jsonb,
  state text not null default 'playing',
  updated_at timestamptz not null default now()
);
alter table public.player_presence add column if not exists trail jsonb not null default '[]'::jsonb;

create table if not exists public.territory_capture_disputes (
  operation_id text primary key,
  candidate_id text not null,
  target_territory_id text,
  user_id uuid not null references auth.users(id) on delete cascade,
  signature text not null,
  status text not null default 'disputed' check (status = 'disputed'),
  candidate_payload jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists territories_regions_gin_idx on public.territories using gin(region_ids);
create index if not exists territories_primary_region_updated_idx on public.territories(primary_region, updated_at desc);
create index if not exists territories_owner_updated_idx on public.territories(owner_id, updated_at desc);
create unique index if not exists territories_active_signature_idx
  on public.territories(signature)
  where signature is not null and status not in ('rejected');
create index if not exists ownership_history_territory_time_idx
  on public.territory_ownership_history(territory_id, captured_at desc);
create index if not exists presence_region_updated_idx
  on public.player_presence(region_id, updated_at desc);

